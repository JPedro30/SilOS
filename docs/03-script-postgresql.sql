-- =============================================================================
-- SCRIPT DE CREACIÓN DE BASE DE DATOS Y TABLAS (PostgreSQL 12+)
-- Proyecto: Sistema de Gestión de Silos y Trazabilidad de Movimientos
-- =============================================================================

-- Eliminar tablas en orden inverso a sus dependencias si existen
DROP TABLE IF EXISTS movimientos CASCADE;
DROP TABLE IF EXISTS silos CASCADE;
DROP TABLE IF EXISTS usuarios CASCADE;
DROP TABLE IF EXISTS roles CASCADE;
DROP TABLE IF EXISTS empresas CASCADE;
DROP TABLE IF EXISTS materiales CASCADE;
DROP TABLE IF EXISTS transportistas CASCADE;

-- =============================================================================
-- 1. TABLA: EMPRESAS
-- =============================================================================
CREATE TABLE empresas (
id_empresa BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
cif VARCHAR(20) NOT NULL UNIQUE,
nombre VARCHAR(100) NOT NULL,
color_hex VARCHAR(7) NOT NULL
);

COMMENT ON TABLE empresas IS 'Clientes propietarios del material en los silos.';
COMMENT ON COLUMN empresas.color_hex IS 'Código de color Hexadecimal (#RRGGBB) para representación gráfica en UI.';

-- =============================================================================
-- 2. TABLA: ROLES
-- =============================================================================
CREATE TABLE roles (
id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
nombre_rol VARCHAR(50) NOT NULL UNIQUE
);

COMMENT ON TABLE roles IS 'Roles del sistema (ROLE_ADMIN, ROLE_TRABAJADOR, ROLE_EMPRESA).';

-- =============================================================================
-- 3. TABLA: USUARIOS
-- =============================================================================
CREATE TABLE usuarios (
id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
id_rol BIGINT NOT NULL,
id_empresa BIGINT,
username VARCHAR(50) NOT NULL UNIQUE,
password VARCHAR(255) NOT NULL,
CONSTRAINT fk_usuario_rol FOREIGN KEY (id_rol) REFERENCES roles(id_rol),
CONSTRAINT fk_usuario_empresa FOREIGN KEY (id_empresa) REFERENCES empresas(id_empresa) ON DELETE SET NULL
);

COMMENT ON TABLE usuarios IS 'Usuarios del sistema para autenticación y autorización.';

-- =============================================================================
-- 4. TABLA: MATERIALES
-- =============================================================================
CREATE TABLE materiales (
id_material BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
tipo_general VARCHAR(50) NOT NULL,
tipo_especifico VARCHAR(50),
nombre VARCHAR(100) NOT NULL
);

COMMENT ON TABLE materiales IS 'Catálogo maestro de granos y productos almacenables.';

-- =============================================================================
-- 5. TABLA: SILOS
-- =============================================================================
CREATE TABLE silos (
id_silo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
id_empresa BIGINT,
id_material BIGINT,
nombre VARCHAR(50) NOT NULL,
capacidad_max NUMERIC(10,2) NOT NULL DEFAULT 500000.00,
cantidad_actual NUMERIC(10,2) NOT NULL DEFAULT 0.00,
habilitado BOOLEAN NOT NULL DEFAULT FALSE,
CONSTRAINT fk_silo_empresa FOREIGN KEY (id_empresa) REFERENCES empresas(id_empresa) ON DELETE SET NULL,
CONSTRAINT fk_silo_material FOREIGN KEY (id_material) REFERENCES materiales(id_material) ON DELETE SET NULL,
CONSTRAINT chk_silo_cantidad_positiva CHECK (cantidad_actual >= 0)
);

COMMENT ON TABLE silos IS 'Infraestructura física de almacenamiento en planta.';

-- =============================================================================
-- 6. TABLA: TRANSPORTISTAS
-- =============================================================================
CREATE TABLE transportistas (
id_transportista BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
matricula_camion VARCHAR(20) NOT NULL UNIQUE,
matricula_remolque VARCHAR(20),
nombre_conductor VARCHAR(150) NOT NULL,
dni_conductor VARCHAR(12) NOT NULL
);

COMMENT ON TABLE transportistas IS 'Ficha actual de camiones y chóferes que acceden a la planta.';

-- Index para búsquedas frecuentes por matrícula
CREATE INDEX idx_transportista_matricula ON transportistas(matricula_camion);

-- =============================================================================
-- 7. TABLA: MOVIMIENTOS (Transaccional)
-- =============================================================================
CREATE TABLE movimientos (
id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
id_empresa BIGINT NOT NULL,
id_silo BIGINT NOT NULL,
id_material BIGINT NOT NULL,
id_transportista BIGINT NOT NULL,
id_usuario BIGINT NOT NULL,
tipo_movimiento CHAR(1) NOT NULL,
peso_entrada NUMERIC(10,2) NOT NULL,
peso_salida NUMERIC(10,2) NOT NULL,
cantidad_neta NUMERIC(10,2) NOT NULL,
fecha_hora_entrada TIMESTAMP NOT NULL,
fecha_hora_salida TIMESTAMP NOT NULL,
humedad_material NUMERIC(4,2),
proteina NUMERIC(4,2),
humedad_ambiental NUMERIC(4,2),
precipitacion NUMERIC(5,2),
conductor_nombre_snapshot VARCHAR(150),
conductor_dni_snapshot VARCHAR(12),
CONSTRAINT fk_mov_empresa FOREIGN KEY (id_empresa) REFERENCES empresas(id_empresa),
CONSTRAINT fk_mov_silo FOREIGN KEY (id_silo) REFERENCES silos(id_silo),
CONSTRAINT fk_mov_material FOREIGN KEY (id_material) REFERENCES materiales(id_material),
CONSTRAINT fk_mov_transportista FOREIGN KEY (id_transportista) REFERENCES transportistas(id_transportista),
CONSTRAINT fk_mov_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario),
CONSTRAINT chk_tipo_movimiento CHECK (tipo_movimiento IN ('E', 'S')),
CONSTRAINT chk_fechas_coherentes CHECK (fecha_hora_salida >= fecha_hora_entrada)
);

COMMENT ON TABLE movimientos IS 'Registro transaccional e inmutable de entradas, salidas y mermas.';

-- Índices estratégicos para optimizar reportes e histórico
CREATE INDEX idx_movimientos_silo ON movimientos(id_silo);
CREATE INDEX idx_movimientos_empresa ON movimientos(id_empresa);
CREATE INDEX idx_movimientos_fechas ON movimientos(fecha_hora_entrada);

